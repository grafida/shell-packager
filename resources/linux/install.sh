#!/bin/sh
#
# Desktop integration for this app, for the current user only (no root needed). It ships inside
# the app's Linux tarball, beside the launcher, and installs into the per-user XDG locations:
#
#   desktop entry  $XDG_DATA_HOME/applications/<id>.desktop   (Exec rewritten to the launcher here)
#   icons          $XDG_DATA_HOME/icons/hicolor/<n>x<n>/apps/<id>.png
#
# The app itself stays where the tarball was extracted. Run it again after moving the folder.
#
#   ./install.sh               install (or refresh) the desktop entry and icons
#   ./install.sh --uninstall   remove them
#
# Generated by grafida/shell-packager.

set -eu

APP_ID=@APP_ID@
NAME=@NAME@
TITLE=@TITLE@

APP_DIR=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd -P)
DATA_HOME=${XDG_DATA_HOME:-$HOME/.local/share}
APPS_DIR=$DATA_HOME/applications
ICONS_DIR=$DATA_HOME/icons/hicolor
DESKTOP=$APPS_DIR/$APP_ID.desktop

refresh() {
    if command -v update-desktop-database >/dev/null 2>&1; then update-desktop-database "$APPS_DIR" 2>/dev/null || true; fi
    if command -v gtk-update-icon-cache >/dev/null 2>&1; then gtk-update-icon-cache -f -t "$ICONS_DIR" 2>/dev/null || true; fi
}

if [ "${1:-}" = "--uninstall" ]; then
    rm -f "$DESKTOP"
    for icon in "$APP_DIR"/icons/hicolor/*/apps/"$APP_ID".png; do
        [ -e "$icon" ] || continue
        size=$(basename "$(dirname "$(dirname "$icon")")")
        rm -f "$ICONS_DIR/$size/apps/$APP_ID.png"
    done
    refresh
    echo "$TITLE: the desktop entry and icons were removed."
    exit 0
fi

[ -x "$APP_DIR/$NAME" ] || { echo "ERROR: $NAME not found beside this script." >&2; exit 1; }
[ -f "$APP_DIR/$APP_ID.desktop" ] || { echo "ERROR: $APP_ID.desktop not found beside this script." >&2; exit 1; }

mkdir -p "$APPS_DIR"
for icon in "$APP_DIR"/icons/hicolor/*/apps/"$APP_ID".png; do
    [ -e "$icon" ] || continue
    size=$(basename "$(dirname "$(dirname "$icon")")")
    mkdir -p "$ICONS_DIR/$size/apps"
    cp "$icon" "$ICONS_DIR/$size/apps/$APP_ID.png"
    chmod 0644 "$ICONS_DIR/$size/apps/$APP_ID.png"
done

# The Desktop Entry spec: an Exec argument with a reserved character is double-quoted, with ",
# `, $ and \ escaped.
exec_path=$(printf '%s' "$APP_DIR/$NAME" | sed 's/[\\"`$]/\\&/g')
tmp=$DESKTOP.tmp
# Only the main entry's Exec; a [Desktop Action …] section keeps its own.
sed "/^\[Desktop Entry\]/,/^\[/ s|^Exec=.*|Exec=\"$(printf '%s' "$exec_path" | sed 's/[|&]/\\&/g')\"|" "$APP_DIR/$APP_ID.desktop" > "$tmp"
chmod 0644 "$tmp"
mv "$tmp" "$DESKTOP"

refresh

echo "$TITLE: installed for the current user."
echo "  Desktop entry: $DESKTOP"
echo "  Launches:      $APP_DIR/$NAME"
echo "Run './install.sh --uninstall' to remove them."

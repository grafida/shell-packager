declare(strict_types=1);

namespace Grafida\ShellPackager\Linux;

use Grafida\ShellPackager\Arch;
use Grafida\ShellPackager\Config;
use Grafida\ShellPackager\PackagerException;

/**
 * An Arch `PKGBUILD` for the Linux tarball (grafida/grafida#87): a text template filled from the app's
 * configuration and from the tarballs already built (their SHA-256 is computed from the files,
 * never typed). Nothing is published; the file is for the AUR or a private repository.
 *
 * It installs the whole tarball under `/opt/<name>` with a `/usr/bin/<name>` symlink to the launcher,
 * the desktop entry in `/usr/share/applications` and the icons in the hicolor theme. The system
 * `webkit2gtk-4.1`, `gtk3`, `hicolor-icon-theme` and `dbus` are declared as dependencies (not repeated in the app's config), and
 * `!strip` keeps makepkg from touching the static launcher, the shell and the phpmicro stub.
 */
final class Pkgbuild
{
    /**
     * @param array<string, string> $tarballs architecture name (x86_64/aarch64) => built tarball
     */
    public static function render(Config $config, string $version, array $tarballs): string
    {
        $options = $config->pkgbuild ?? throw new PackagerException('There is no linux.pkgbuild section in the packaging configuration.');

        if ($tarballs === []) {
            throw new PackagerException('No tarball to make a PKGBUILD for.');
        }

        if ($config->desktop === null) {
            throw new PackagerException('A PKGBUILD installs the desktop entry: linux.desktop is required.');
        }

        // pkgver may not contain a hyphen; 1.0.0-rc1 is 1.0.0_rc1 for pacman, the source URL keeps the real one.
        $pkgver = str_replace('-', '_', $version);

        if (preg_match('/^[A-Za-z0-9][A-Za-z0-9._+]*$/', $pkgver) !== 1) {
            throw new PackagerException("'{$version}' cannot be a pacman version.");
        }

        if (preg_match('/^[a-z0-9@_+][a-z0-9@._+-]*$/', $config->linuxName) !== 1) {
            throw new PackagerException("linux.name '{$config->linuxName}' is not a valid pacman package name (lower-case letters, digits, @ . _ + -).");
        }

        if (preg_match('/^[A-Za-z0-9][A-Za-z0-9._-]*$/', $config->appId) !== 1) {
            throw new PackagerException("The manifest id '{$config->appId}' cannot be put in a PKGBUILD.");
        }

        $archs  = [];
        $source = [];
        $sums   = [];

        foreach ([Arch::X86_64, Arch::Aarch64] as $arch) {
            if (!isset($tarballs[$arch->value])) {
                continue;
            }

            $file = $tarballs[$arch->value];

            if (!is_file($file)) {
                throw new PackagerException("The {$arch->value} tarball {$file} has not been built.");
            }

            $url = strtr($options->source, [
                '{name}'    => $config->linuxName,
                '{version}' => $version,
                '{arch}'    => $arch->value,
                '{debarch}' => $arch->debian(),
            ]);

            $archs[]  = $arch->value;
            // makepkg names the download by the part before '::' and unpacks .tar.gz from it.
            $source[] = "source_{$arch->value}=(" . self::q("{$config->linuxName}-{$pkgver}-{$arch->value}.tar.gz::{$url}") . ')';
            $sums[]   = "sha256sums_{$arch->value}=(" . self::q((string) hash_file('sha256', $file)) . ')';
        }

        // The tarball's top-level folder is linux.name.
        $top     = $config->linuxName;
        $id      = $config->appId;
        $depends = array_values(array_unique([...PkgbuildConfig::DEFAULT_DEPENDS, ...$options->depends]));
        $lines   = [];

        if ($options->maintainer !== null) {
            $lines[] = '# Maintainer: ' . $options->maintainer;
        }

        $lines[] = '# Generated by shell-packager from the ' . $top . ' ' . $version . ' tarball. Do not edit by hand.';
        $lines[] = 'pkgname=' . self::q($config->linuxName);
        $lines[] = 'pkgver=' . self::q($pkgver);
        $lines[] = 'pkgrel=' . $options->pkgrel;
        $lines[] = 'pkgdesc=' . self::q($options->description);
        $lines[] = 'arch=(' . implode(' ', array_map(self::q(...), $archs)) . ')';
        $lines[] = 'url=' . self::q($options->url);
        $lines[] = 'license=(' . implode(' ', array_map(self::q(...), $options->license)) . ')';
        $lines[] = 'depends=(' . implode(' ', array_map(self::q(...), $depends)) . ')';

        if ($options->optdepends !== []) {
            $lines[] = 'optdepends=(' . implode(' ', array_map(self::q(...), $options->optdepends)) . ')';
        }

        // Stripping or debug-splitting would rewrite the static launcher, the shell and the SFX stub.
        $lines[] = "options=('!strip' '!debug' '!emptydirs')";
        array_push($lines, ...$source, ...$sums);
        $lines[] = '';
        $lines[] = 'package() {';
        $lines[] = '    cd "$srcdir/' . $top . '"';
        $lines[] = '';
        $lines[] = '    # The program, whole: the launcher finds the shell, the worker and its .phar beside itself.';
        $lines[] = '    install -d "$pkgdir/opt/$pkgname"';
        $lines[] = '    cp -a . "$pkgdir/opt/$pkgname/"';
        $lines[] = '    rm -rf "$pkgdir/opt/$pkgname/install.sh" "$pkgdir/opt/$pkgname/icons" "$pkgdir/opt/$pkgname/' . $id . '.desktop"';
        $lines[] = '    install -d "$pkgdir/usr/bin"';
        $lines[] = '    ln -s "/opt/$pkgname/' . $top . '" "$pkgdir/usr/bin/$pkgname"';
        $lines[] = '';
        $lines[] = '    # Desktop integration: Exec=' . $top . ' resolves through /usr/bin.';
        $lines[] = '    install -Dm644 ' . self::q($id . '.desktop') . ' "$pkgdir/usr/share/applications/' . $id . '.desktop"';
        $lines[] = '    for icon in icons/hicolor/*/apps/' . $id . '.png; do';
        $lines[] = '        install -Dm644 "$icon" "$pkgdir/usr/share/${icon}"';
        $lines[] = '    done';
        $lines[] = '}';

        return implode("\n", $lines) . "\n";
    }

    public static function outputPath(Config $config): string
    {
        $output = ($config->pkgbuild ?? throw new PackagerException('There is no linux.pkgbuild section in the packaging configuration.'))->output;

        return str_starts_with($output, '/') ? $output : $config->root . '/' . $output;
    }

    /** A bash single-quoted word. */
    private static function q(string $value): string
    {
        return "'" . str_replace("'", "'\\''", $value) . "'";
    }
}
